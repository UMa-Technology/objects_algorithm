#!/usr/bin/env bash
#
# Generate the forwarding source files under ios/Classes/generated and macos/Classes/generated.
#
# Why the forwarding layer: CocoaPods s.source_files doesn't accept relative paths outside the
# pod directory, while the C++ sources must stay in src/ as the single source of truth (the
# Android and Windows CMake builds compile them directly). The official plugin_ffi template
# does the same: a layer of one-line #include forwarding files under Classes/, letting the
# preprocessor pull in the real sources. Rerun this script after adding new AA+ source files.
#
# This script only owns the generated/ subdirectory; hand-written files under Classes/ are untouched.

set -euo pipefail

PLUGIN_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PLUGIN_ROOT"

# AATest.cpp is AA+'s upstream test driver with an int main().
# On Android/Windows it sits unreferenced in a static library and is harmless, but on Apple
# platforms every source file is compiled straight into the pod target, and that main would
# clash with the host app's main. It must be excluded.
EXCLUDE_RE='AATest\.cpp$'

# List every aainterface header that has a matching .cpp implementation.
# Only those count: KPCAAPlanetaryPhenomena.h has declarations but no .cpp, and putting its
# functions in the keepalive table fails at link time (undefined symbol).
interface_headers_with_impl() {
  local h base
  for h in src/aainterface/*.h; do
    base="$(basename "$h" .h)"
    [ -f "src/aainterface/$base.cpp" ] && echo "$base"
  done
}

# Extract the extern "C" function names that actually exist from the headers.
# Comments must be stripped first: KPCAARiseTransitSet2.h has a commented-out CalculateMoon
# declaration, and picking it up would put it in the keepalive table and break the link.
extract_symbols() {
  local base
  for base in $(interface_headers_with_impl); do
    perl -0777 -pe 's{/\*.*?\*/}{}gs; s{//[^\n]*}{}g' "src/aainterface/$base.h"
  done \
    | grep -oE '\bKPCAA[A-Za-z0-9_]*[[:space:]]*\(' \
    | sed -E 's/[[:space:]]*\($//' \
    | sort -u
}

emit_platform() {
  local plat="$1"
  local out="$plat/Classes/generated"

  rm -rf "$out"
  mkdir -p "$out"

  local count=0
  local dir path base

  for dir in aaplus aainterface; do
    for path in src/$dir/*.cpp; do
      base="$(basename "$path" .cpp)"
      [[ "$path" =~ $EXCLUDE_RE ]] && continue

      # Prefix file names with the directory so that if aaplus/ and aainterface/ ever share
      # a file name, the two .o files don't collide in the same target.
      {
        echo "// Generated by tool/gen_darwin_sources.sh. Do not edit."
        echo "// The real source is src/$dir/$base.cpp."
        echo "#include \"../../../src/$dir/$base.cpp\""
      } > "$out/${dir}_${base}.cpp"

      count=$((count + 1))
    done
  done

  {
    cat <<'HEADER'
// Generated by tool/gen_darwin_sources.sh. Do not edit.
//
// Keeping symbols alive on Apple platforms has two hurdles:
//
// 1) Archive member selection. The Dart side looks up KPCAA* symbols at runtime via
//    DynamicLibrary.process() + dlsym; nothing references them at link time. CocoaPods builds
//    this pod as a static library, and the linker discards unreferenced archive members
//    wholesale, so the forwarding units never make it into the final binary.
//
// 2) Dead stripping. Even once pulled in, the host app target defaults to
//    DEAD_CODE_STRIPPING=YES in Release and strips unreferenced functions again. That's a link
//    setting of the host target, out of reach of the plugin's pod_target_xcconfig (the pod is a
//    static library and never links).
//
// The function address table below solves both: taking an address is a link-time reference,
// so the archive members get pulled in and survive dead stripping. The aaplus implementations
// are referenced by aainterface and survive transitively, so they need no entries.
//
// This file is itself an archive member and needs a reference from the host to start the chain:
// that is ObjectsAlgorithmPlugin (pubspec declares it as pluginClass, and the Flutter-generated
// GeneratedPluginRegistrant references it), see ../ObjectsAlgorithmPlugin.m.
//
// The function names aren't hand-written; they're extracted from src/aainterface/*.h, see
// gen_darwin_sources.sh for the rules.

HEADER

    local base
    for base in $(interface_headers_with_impl); do
      echo "#include \"../../../src/aainterface/$base.h\""
    done

    echo ""
    echo "__attribute__((used, visibility(\"default\")))"
    echo "const void *const kObjectsAlgorithmKeepAlive[] = {"

    local sym
    while read -r sym; do
      echo "    (const void *)&$sym,"
    done < <(extract_symbols)

    echo "};"
    echo ""
    echo "extern \"C\" __attribute__((used, visibility(\"default\")))"
    echo "const void *objects_algorithm_keepalive_anchor(void) {"
    echo "  return kObjectsAlgorithmKeepAlive;"
    echo "}"
  } > "$out/objects_algorithm_keepalive.cpp"

  echo "$plat/Classes/generated: $count forwarding files, keepalive covers $(extract_symbols | wc -l | tr -d ' ') symbols"
}

emit_platform ios
emit_platform macos
